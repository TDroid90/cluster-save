export function mergeContent(remote) {
  if (!remote || typeof remote !== "object") return defaultContent;
  const merged = { ...defaultContent };
  for (const key of ["general", "images", "theme", "social"]) {
    merged[key] = { ...defaultContent[key], ...(remote[key] || {}) };
  }
  for (const key of ["nav", "heroPoints", "highlights", "services", "prices", "businessItems", "process", "benefits", "faqs"]) {
    if (Array.isArray(remote[key]) && remote[key].length) merged[key] = remote[key];
  }
  return merged;
}

export function imageSrc(value) {
  if (!value) return "";
  const match = String(value).match(/drive\.google\.com\/(?:file\/d\/|open\?id=|uc\?[^#]*?id=)([-\w]+)/);
  return match ? `/api/image?id=${encodeURIComponent(match[1])}` : value;
}
